import { describe, it, expect } from 'vitest'
import { isUuid } from '@/lib/is-uuid'

describe('isUuid', () => {
  it('accepts a uuid generated by the database', () => {
    expect(isUuid('cd9c54e5-1b6f-4c4e-9a3e-2f1d8b7a6c50')).toBe(true)
  })
  it('accepts an uppercase uuid', () => {
    expect(isUuid('CD9C54E5-1B6F-4C4E-9A3E-2F1D8B7A6C50')).toBe(true)
  })
  it.each([
    ['an empty string', ''],
    ['a random string', 'abc'],
    ['a uuid without dashes', 'cd9c54e51b6f4c4e9a3e2f1d8b7a6c50'],
    ['a uuid with a non-hex character', 'gd9c54e5-1b6f-4c4e-9a3e-2f1d8b7a6c50'],
    [
      'a uuid with surrounding whitespace',
      ' cd9c54e5-1b6f-4c4e-9a3e-2f1d8b7a6c50 ',
    ],
    ['a uuid followed by SQL', "cd9c54e5-1b6f-4c4e-9a3e-2f1d8b7a6c50' or 1=1"],
    ['a number', 42],
    ['null', null],
    ['undefined', undefined],
    ['an object', { id: 'cd9c54e5-1b6f-4c4e-9a3e-2f1d8b7a6c50' }],
  ])('rejects %s', (_, value) => {
    expect(isUuid(value)).toBe(false)
  })
})
